export const diagnosticBank: Record<number, DiagnosticQuestion[]> =
  Object.fromEntries(
    Object.entries(banks).map(([course, rows]) => [
      Number(course),
      rows.map(
        ([lesson, skill, prompt, choices, answer, explanation], index) => {
          const rotation =
            Number(course) > 5 ? (index + 1) % choices.length : 0;
          return {
            id: `c${course}-q${index + 1}`,
            level: Math.floor(index / 4) + 1,
            lesson,
            skill,
            prompt,
            choices: [
              ...choices.slice(rotation),
              ...choices.slice(0, rotation),
            ],
            answer: (answer - rotation + choices.length) % choices.length,
            explanation,
          };
        },
      ),
    ]),
  );
